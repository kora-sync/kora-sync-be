package com.minierp.kora_sync.controller;

import com.minierp.kora_sync.dto.MarkAllReadResponse;
import com.minierp.kora_sync.dto.NotificationResponse;
import com.minierp.kora_sync.dto.PageResponse;
import com.minierp.kora_sync.dto.UnreadCountResponse;
import com.minierp.kora_sync.security.CurrentCompany;
import com.minierp.kora_sync.security.RequiresManager;
import com.minierp.kora_sync.service.NotificationService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.security.SecurityRequirement;
import io.swagger.v3.oas.annotations.tags.Tag;
import lombok.RequiredArgsConstructor;
import org.springdoc.core.annotations.ParameterObject;
import org.springframework.data.domain.Pageable;
import org.springframework.data.web.PageableDefault;
import org.springframework.http.HttpStatus;
import org.springframework.http.ProblemDetail;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;

import java.util.UUID;

@RestController
@RequestMapping("/api/notifications")
@RequiredArgsConstructor
@RequiresManager
@SecurityRequirement(name = "bearerAuth")
@Tag(name = "Notifications", description = "Alerts generated by the system, such as low stock and bills due")
public class NotificationController {

    private final NotificationService notificationService;

    @GetMapping
    @ResponseStatus(HttpStatus.OK)
    @Operation(
            summary = "List notifications",
            description = "Returns the notifications of the company, newest first. The order cannot be changed.")
    public PageResponse<NotificationResponse> list(
            @CurrentCompany UUID companyId,
            @Parameter(description = "When true, returns only the unread ones. Otherwise returns all", example = "true")
            @RequestParam(required = false) Boolean unread,
            @ParameterObject @PageableDefault(size = 10) Pageable pageable) {
        return notificationService.findAll(companyId, unread, pageable);
    }

    @GetMapping("/unread-count")
    @ResponseStatus(HttpStatus.OK)
    @Operation(
            summary = "Count unread notifications",
            description = "Returns how many notifications are still unread, for a badge in the interface.")
    public UnreadCountResponse unreadCount(@CurrentCompany UUID companyId) {
        return notificationService.countUnread(companyId);
    }

    @PostMapping("/{id}/read")
    @ResponseStatus(HttpStatus.OK)
    @Operation(
            summary = "Mark a notification as read",
            description = "Marks one notification as read. Marking one that is already read changes nothing. "
                    + "The mark is shared by every manager and admin of the company.")
    @ApiResponses({
            @ApiResponse(responseCode = "404", description = "Notification not found in this company",
                    content = @Content(schema = @Schema(implementation = ProblemDetail.class)))
    })
    public NotificationResponse markAsRead(
            @CurrentCompany UUID companyId,
            @Parameter(description = "Notification identifier", example = "5f3a9c1e-7b2d-4e86-a4c0-2d8e6b1f9a73")
            @PathVariable UUID id) {
        return notificationService.markAsRead(companyId, id);
    }

    @PostMapping("/read-all")
    @ResponseStatus(HttpStatus.OK)
    @Operation(
            summary = "Mark all notifications as read",
            description = "Marks every unread notification of the company as read and says how many changed.")
    public MarkAllReadResponse markAllAsRead(@CurrentCompany UUID companyId) {
        return notificationService.markAllAsRead(companyId);
    }
}